// Writes docs/audio-scripts.md from src/content/audioManifest.js.
// Edit the manifest, then run: npm run audio-scripts
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { root } from './lib/vocab.mjs';

const { default: clips } = await import(pathToFileURL(path.join(root, 'src', 'content', 'audioManifest.js')).href);

const roomNames = {
  start: 'Start screen',
  room1: 'Room 1 - Message Room',
  room2: 'Room 2 - Engine Room',
  room3: 'Room 3 - Garden Room',
  room4: 'Room 4 - Science Room',
  room5: 'Room 5 - Robot Room',
  final: 'Radio Room',
};

const total = clips.reduce((s, c) => s + c.seconds, 0);
let md = `# Audio scripts

Generated from \`src/content/audioManifest.js\` by \`npm run audio-scripts\`. Do not edit this file by hand: change the manifest and run the script again.

Status: **DRAFT, waiting for teacher approval before recording.**

## How to record

- ${clips.length} clips, about ${Math.round(total / 60)} minutes of audio in total.
- Two speakers: **Teacher A** (Helen, Holly) and **Teacher B** (Pip, William, Michael, narrator).
- Speak clearly at a slow-normal speed. Make a short pause at every full stop.
- Read the words exactly as written. The game shows the same words as the transcript.
- Save as \`.mp3\` (mono, 64-128 kbps is enough) in \`public/audio/\` with the filename below.
- Run \`npm run check-content\` to see which files are still missing.
- Pip is a friendly robot: a warm voice, maybe a little higher. Not scary, no effects needed.
- "Plays" is how many times the child can play the clip ("no limit" or a number). Practice mode removes the limit.

| # | File | Where | Speaker | Target length | Plays |
|---|---|---|---|---|---|
`;
clips.forEach((c, i) => {
  md += `| ${i + 1} | \`${c.file}\` | ${roomNames[c.room] || c.room} | ${c.speaker} | ${c.seconds} s | ${c.maxPlays ?? 'no limit'} |\n`;
});

md += '\n## Scripts\n';
clips.forEach((c, i) => {
  md += `\n### ${i + 1}. \`${c.file}\`\n\n`;
  md += `- Where: ${roomNames[c.room] || c.room}\n- Speaker: ${c.speaker}\n- Target length: about ${c.seconds} seconds\n\n`;
  const lines = c.transcript.split(/(?=\b(?:Helen|William|Michael): )/);
  for (const line of lines) md += `> ${line.trim()}\n>\n`;
  md = md.replace(/>\n$/, '');
});

fs.writeFileSync(path.join(root, 'docs', 'audio-scripts.md'), md);
console.log(`Wrote docs/audio-scripts.md (${clips.length} clips, ${total} seconds).`);
